namespace DIR.Lib.Tests;

/// <summary>
/// The square root's vinculum must continue the radical glyph's flag with no gap, no vertical offset
/// and a shared crisp top edge. Reported from mdcat (Sixel, STIX Two Math at 32 px) and the 96 px
/// baselines: a near-empty column between flag and bar (the flag's antialiased right end), and a bar
/// whose solid top row sat on the flag's antialiased top row, so the bar read as half a pixel high.
///
/// <para>Each case renders a scene to RGBA and finds the join from the layout's own numbers: the
/// <see cref="SqrtBox.JoinAt"/> the radical's draw takes its geometry from, asked at the pen the scene drew
/// the radical at (the flag's top row and band height, its rightmost full-coverage column, the bar's end),
/// never by searching the image. The assertions then read the pixels there.</para>
///
/// <para>Both fonts run every assertion. DejaVu Sans has no MATH table, so it takes the scaled-glyph
/// path (2), and path 1 with its unstretched base glyph for the 24 px index scene; its hinter already
/// puts the flag's top on a pixel row, so the snap is a no-op there and only the join changed. STIX Two
/// Math takes path 2 for the five scenes the report names (its MATH size variants overshoot those
/// radicands by more than 10%), so two more scenes reach path 1: a size variant
/// (<c>sqrt-paren-frac</c> at 32 and 24 px) and the assembly (<c>sqrt-nested-frac</c>).</para>
///
/// <para>Layout invariants hold against the radical as commit fe09d4a drew it (data in
/// <c>RadicalJoinTests.Before.cs</c>, generated by tools/gen-radical-join-before): the bar's band is never
/// more rows than the flag's own stroke; the radical's height and depth grow at most 2 px (and shrink at
/// most 2 px, or 3 below 21.3 px where the cap at the flag's stroke trimmed the band); the radicand never has
/// fewer clear rows under the bar than before, and always has at least one. They are swept densely over the
/// sizes Console.Lib draws math at, since the review rounds found their bugs between the join assertions'
/// three sizes.</para>
///
/// <para>Until fe09d4a the data was the radical before this rework (commit e6778fc), and the review
/// rounds' cases below were found against it: "the base" in their comments is that commit. fe09d4a, the
/// rework itself, keeps every one of them.</para>
/// </summary>
public sealed partial class RadicalJoinTests
{
    /// <summary>How far, in alpha, the bar may differ from the flag's column on any row.</summary>
    private const int AlphaTolerance = 8;

    /// <summary>The most the radical's height or depth may move from before: 2 px, plus a thousandth for
    /// float noise, since a drift of exactly two pixels can come out as 8.798f - 6.798f = 2.0000005.</summary>
    private const float DriftLimitPx = 2.001f;

    /// <summary>How far a radical may shrink below 21.3 px where the cap at the flag's stroke trimmed its band
    /// (see <see cref="SweepHeightAndDepthDriftAtMostTwoPixels"/>), with the same thousandth for float noise.</summary>
    private const float SmallSizeShrinkLimitPx = 3.001f;

    private static readonly Dictionary<string, string> FontPaths = new()
    {
        ["STIX2Math"] = Path.Combine(AppContext.BaseDirectory, "Fonts", "STIX2Math.otf"),
        ["DejaVuSans"] = Path.Combine(AppContext.BaseDirectory, "Fonts", "DejaVuSans.ttf"),
    };

    /// <summary>96 px is the baselines' size; 32 px is Console.Lib's Sixel math, and 24 px about where it
    /// shrinks a wide formula to fit the terminal.</summary>
    private static readonly int[] Sizes = [96, 32, 24];

    private static readonly string[] Scenes =
    [
        "sqrt-x2-plus-y2", "sqrt-2", "sqrt-frac-a-b", "quadratic-formula", "index-box-api",
        "sqrt-paren-frac", "sqrt-nested-frac",
    ];

    public static IEnumerable<TheoryDataRow<string, int, string>> Cases()
    {
        foreach (var font in FontPaths.Keys)
            foreach (var size in Sizes)
                foreach (var scene in Scenes)
                    yield return new TheoryDataRow<string, int, string>(font, size, scene);
    }

    /// <summary>
    /// No column from the flag's last full column to the bar's end carries less ink than that column:
    /// the flag's antialiased right end is not left as a lighter column between flag and bar.
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void NoColumnAtTheJoinIsLighterThanTheBar(string font, int size, string scene)
    {
        var r = Render(font, size, scene);
        var reference = r.ColumnSum(r.Join.FlagLastFullX);
        for (var x = r.Join.FlagLastFullX; x < r.Join.BarEndX; x++)
        {
            var sum = r.ColumnSum(x);
            sum.ShouldBeGreaterThanOrEqualTo(reference - AlphaTolerance * r.Join.FlagRows,
                $"column {x} (flag's last full column {r.Join.FlagLastFullX}, bar ends {r.Join.BarEndX}) " +
                $"has {sum} alpha down the flag's band against the flag's {reference}");
        }
    }

    /// <summary>
    /// Every column of the bar, and of the flag's filled-in end, has the flag's last full column's alpha on
    /// every row of the band and on the row above it: the same top edge and weight, so the bar is neither
    /// offset from the flag nor thinner than it. The row below the band is compared too, which is what
    /// would catch a bar thicker than the flag, but only up to the bar's first column: over the radicand
    /// that row can hold the radicand's own antialiased top, which is not the bar.
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void BarRepeatsTheFlagsLastFullColumn(string font, int size, string scene)
    {
        var r = Render(font, size, scene);
        var j = r.Join;
        for (var x = j.FlagLastFullX + 1; x < j.BarEndX; x++)
        {
            var lastRow = x <= j.BarStartX ? j.FlagTopY + j.FlagRows : j.FlagTopY + j.FlagRows - 1;
            for (var y = j.FlagTopY - 1; y <= lastRow; y++)
            {
                var flag = r.Alpha(j.FlagLastFullX, y);
                var bar = r.Alpha(x, y);
                Math.Abs(bar - flag).ShouldBeLessThanOrEqualTo(AlphaTolerance,
                    $"column {x}, row {y} (flag band {j.FlagTopY}..{j.FlagTopY + j.FlagRows - 1}): " +
                    $"bar alpha {bar}, flag's column {flag}");
            }
        }
    }

    /// <summary>
    /// The flag's top row is fully covered and nothing sits in the row above it: the top edge is snapped
    /// to a pixel row rather than antialiased across two.
    /// </summary>
    [Theory]
    [MemberData(nameof(Cases))]
    public void FlagTopRowIsFullyCovered(string font, int size, string scene)
    {
        var r = Render(font, size, scene);
        var j = r.Join;
        r.Alpha(j.FlagLastFullX, j.FlagTopY).ShouldBeGreaterThanOrEqualTo(240,
            $"flag's top row {j.FlagTopY} at its last full column {j.FlagLastFullX}");
        r.Alpha(j.FlagLastFullX, j.FlagTopY - 1).ShouldBe(0,
            $"row {j.FlagTopY - 1}, above the flag's top, at column {j.FlagLastFullX}");
    }

    /// <summary>
    /// The sizes the layout invariants are swept over: every integer size from 8 to 40 px, and densely, in
    /// addition, the ranges Console.Lib's shrink loop walks continuously (it shrinks math by at least half a
    /// pixel a step, down to two thirds of the size it starts from: about 6.7 to 10 px half-block, 8 to 12 px
    /// sextant, 21.3 to 32 px Sixel), plus 48, 64, 72 and 96. Review round 2 found its bugs at fractional
    /// and sub-8 px sizes that the integer sweep never reached. Computed in double and rounded, exactly as tools/gen-radical-join-before computes
    /// them, so the floats compare equal. The exact-pixel join assertions above stay at 24, 32 and 96 px.
    /// </summary>
    private static readonly float[] SweepSizes =
    [
        .. Enumerable.Range(8, 33).Select(i => (float)i)
            .Concat(Enumerable.Range(0, 109).Select(i => (float)Math.Round(6.6 + i * 0.05, 2)))
            .Concat(Enumerable.Range(0, 108).Select(i => (float)Math.Round(21.3 + i * 0.1, 1)))
            .Concat([48f, 64f, 72f, 96f])
            .Distinct(),
    ];

    private static readonly string[] SweepScenes =
        ["sqrt-2", "sqrt-x", "sqrt-paren-frac", "sqrt-nested-frac", "sqrt-frac-a-b"];

    /// <summary>Radicals with something above them that the canvas's margin does not separate them from: a
    /// fraction's rule over its denominator, and a superscript's top, which is the canvas's edge. Swept over
    /// <see cref="SweepSizes"/> as well, and in the before-data.</summary>
    private static readonly string[] ContextScenes =
    [
        "frac-1-sqrt-x", "frac-1-sqrt-frac-a-b", "x-sup-sqrt-y",
        // Radicands whose ink may start further above their reported height (review round 1, Q1).
        "frac-1-sqrt-hat-x", "frac-1-sqrt-sum-x", "frac-1-sqrt-paren-x",
    ];

    /// <summary>Below this size, the floor of Console.Lib's Sixel range, a radical may shrink 3 px where the
    /// stroke cap trimmed its band (see <see cref="SweepHeightAndDepthDriftAtMostTwoPixels"/>).</summary>
    private const float SmallSizeShrinkBelow = 21.3f;

    /// <summary>
    /// The radical flag's stroke thickness in em, measured without SqrtBox: down the rightmost full column
    /// of the font's own radical glyph rendered at 1000 px, its coverage summed. STIX Two Math's base glyph,
    /// its four size variants and its assembly's top part all measure 0.068 em, DejaVu Sans's 0.047.
    /// </summary>
    private static readonly Dictionary<string, float> FlagStrokeEm =
        FontPaths.ToDictionary(kv => kv.Key, kv => MeasureFlagStrokeEm(kv.Value));

    private static float MeasureFlagStrokeEm(string fontPath)
    {
        const float pixelsPerEm = 1000f;
        var bm = new ManagedFontRasterizer().RasterizeGlyph(fontPath, pixelsPerEm, new System.Text.Rune(0x221A));
        int Alpha(int x, int y) => bm.Rgba[(y * bm.Width + x) * 4 + 3];
        var top = 0;
        while (Enumerable.Range(0, bm.Width).All(x => Alpha(x, top) == 0)) top++;
        var plateau = Enumerable.Range(0, bm.Width).Max(x => Alpha(x, top));
        var last = bm.Width - 1;
        while (Alpha(last, top) < plateau - AlphaTolerance) last--;
        var coverage = 0f;
        for (var y = top; y < bm.Height && Alpha(last, y) > 0; y++) coverage += Alpha(last, y) / 255f;
        return coverage / pixelsPerEm;
    }

    /// <summary>Every point of <see cref="BeforePoints"/> rendered once, for the sweep facts: the sweep, the
    /// review rounds' named points, and the join cases.</summary>
    private static readonly Lazy<Swept[]> SweptPoints = new(() =>
    [
        .. BeforePoints.Select(p =>
        {
            var r = Render(p.Font, p.Size, p.Scene);
            return new Swept(p, r.Sqrt.Height, r.Sqrt.Depth, r.ClearRowsUnderBar(), r.ClearRowsAboveBar(), r.Join.FlagRows, MaxBandRows(p.Font, r),
                r.Sqrt.StrokeCapTrimmedBand,
                r.Alpha(r.Join.FlagLastFullX, r.Join.FlagTopY), r.Alpha(r.Join.FlagLastFullX, r.Join.FlagTopY - 1),
                r.GlyphPastDepth, r.RowsAboveHeight, r.RadicalOnCanvas, InkCutOff(p.Font, p.Size, p.Scene, r.Image),
                r.JoinBreak(), RgbaHash(r.Image), r.Join.InkRaise,
                p.Scene == "index-box-api" ? IndexClearanceAt(p.Font, p.Size, r) : null);
        }),
    ]);

    /// <summary>The most rows the flag's own stroke touches at the size this radical's glyph was drawn at.
    /// A stroke t px thick whose top is snapped to a row touches ceil(t) rows; 0.1 px absorbs the 1000 px
    /// measurement's error, and a hinter rounding the stroke to whole pixels never exceeds it.</summary>
    private static int MaxBandRows(string font, Rendered r) =>
        (int)MathF.Ceiling(FlagStrokeEm[font] * r.Sqrt.RadicalGlyphSize + 0.1f);

    /// <param name="CapTrimmed">Whether the cap at the flag's own stroke trimmed the band
    /// (<see cref="SqrtBox.StrokeCapTrimmedBand"/>).</param>
    /// <param name="FlagTopAlpha">The flag's top row at its last full column.</param>
    /// <param name="AboveFlagAlpha">The row above it, at the same column.</param>
    /// <param name="GlyphPastDepth">How far the glyph's last row reaches past the reported depth
    /// (<see cref="Rendered.GlyphPastDepth"/>).</param>
    /// <param name="RowsAboveHeight">Whole rows the bar sits above the reported height
    /// (<see cref="Rendered.RowsAboveHeight"/>).</param>
    /// <param name="RadicalOnCanvas">Whether the glyph and bar lie on the canvas
    /// (<see cref="Rendered.RadicalOnCanvas"/>).</param>
    /// <param name="InkCutOff">Alpha the canvas edge cut off (<see cref="InkCutOff(string, float, string, RgbaImage)"/>).</param>
    /// <param name="JoinBreak">Where the bar fails to continue the flag, or null (<see cref="Rendered.JoinBreak"/>).</param>
    /// <param name="RgbaHash">The rendered scene's size and pixels, hashed (<see cref="RgbaHash"/>).</param>
    /// <param name="InkRaise">Rows the radicand's ink raised bar and glyph (<see cref="SqrtBox.RadicalJoin.InkRaise"/>).</param>
    /// <param name="IndexClear">In the index scene, the clear pixels between the index and the glyph
    /// (<see cref="IndexClearance"/>); null elsewhere.</param>
    /// <param name="ClearAbove">Clear rows between the bar and the ink above it (<see cref="Rendered.ClearRowsAboveBar"/>).</param>
    private sealed record Swept(BeforePoint Before, float Height, float Depth, int ClearRows, int ClearAbove, int BandRows, int MaxBandRows,
        bool CapTrimmed, int FlagTopAlpha, int AboveFlagAlpha, float GlyphPastDepth, int RowsAboveHeight,
        bool RadicalOnCanvas, long InkCutOff, string? JoinBreak, ulong RgbaHash, int InkRaise, int? IndexClear)
    {
        public bool Touches => ClearRows == 0;

        public override string ToString() => $"{Before.Font} {Before.Scene} {Before.Size} px";
    }

    /// <summary>The before data holds every point of the sweep, so a point cannot drop out of it unnoticed.</summary>
    [Fact]
    public void BeforeDataCoversTheSweep()
    {
        var missing = (from font in FontPaths.Keys
                       from scene in SweepScenes.Concat(ContextScenes).Append("index-box-api")
                       from size in SweepSizes
                       where !BeforePoints.Any(p => p.Font == font && p.Scene == scene && p.Size == size)
                       select $"{font} {scene} {size} px").ToList();
        missing.ShouldBeEmpty("sweep points with no before data:" + Environment.NewLine + string.Join(Environment.NewLine, missing));
    }

    /// <summary>
    /// Across the sweep the bar's band is never more rows than the flag's own stroke touches. Where the flag
    /// is no wider than the stem (review round 2, B1) the band ran down the whole stem, 19 to 31 rows drawn
    /// over the radicand; where the stroke is under a pixel (B3) it kept four soft rows. Every failing
    /// point is listed in the one message.
    /// </summary>
    [Fact]
    public void SweepBandIsNeverMoreRowsThanTheFlagsStroke()
    {
        var failures = SweptPoints.Value
            .Where(s => s.BandRows > s.MaxBandRows)
            .Select(s => $"{s}: band {s.BandRows} rows, the flag's stroke touches at most {s.MaxBandRows}")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>
    /// Across the sweep the flag's top row is fully covered at its last full column and the row above it is
    /// empty, as <see cref="FlagTopRowIsFullyCovered"/> asserts at 24, 32 and 96 px. Below about 19 px the
    /// flag's stroke is thinner than a pixel (under 0.9 px in both fonts), so its snapped top covered only
    /// part of its row: 510 of the 2401 points had a top row of 83 to 238 alpha, a grey bar where the old
    /// rule drew an opaque one. A one-row band short of full coverage is now drawn one pixel thick. Every
    /// failing point is listed in the one message.
    /// </summary>
    [Fact]
    public void SweepFlagTopRowIsFullyCovered()
    {
        // In ContextScenes the row above the flag can be another box's ink, a fraction's rule; whether the
        // bar crowds it is InContextTheBarNeverCrowdsWhatIsAboveIt's question.
        var failures = SweptPoints.Value
            .Where(s => s.FlagTopAlpha < 240 || (s.AboveFlagAlpha != 0 && !ContextScenes.Contains(s.Before.Scene)))
            .Select(s => $"{s}: flag's top row {s.FlagTopAlpha}, the row above {s.AboveFlagAlpha}, band {s.BandRows} rows")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>
    /// Across the sweep the radical's height and depth, which a parent fraction or row lays out against,
    /// grow at most 2 px from before at every size, and shrink at most 2 px, with one exception. Below
    /// 21.3 px a radical may shrink by up to 3 px at a point where the cap at the flag's own stroke trimmed
    /// the band (<see cref="ShrinkLimitPx"/>): the scan down the flag's column ran on into the stem, or into
    /// the curve under a flag less than a pixel thick, and the bar and the rows reserved for it were cut back
    /// to the stroke's own, so the radical can come out shorter than the old one. Everywhere else the 2 px
    /// limit holds, so a shrink for any other reason still fails. The allowance was set against 619f0e4's
    /// data, whose x was upright: there STIX <c>\sqrt{x}</c> at 7.6 to 7.7 px shrank 3 px. Against e6778fc's
    /// italic x those points shrink 2 px, and no point of the sweep shrinks by more than 2 px; the 3 px limit
    /// is unchanged, now against fe09d4a's data, which the rework itself produced. Every failing point is
    /// listed in the one message.
    /// </summary>
    [Fact]
    public void SweepHeightAndDepthDriftAtMostTwoPixels()
    {
        static bool Drifts(float before, float after, Swept s)
        {
            var delta = after - before;
            return delta > DriftLimitPx || delta < -ShrinkLimitPx(s);
        }

        var failures = SweptPoints.Value
            .Where(s => Drifts(s.Before.Height, s.Height, s) || Drifts(s.Before.Depth, s.Depth, s))
            .Select(s => $"{s}: height {s.Before.Height} -> {s.Height}, depth {s.Before.Depth} -> {s.Depth}, " +
                         $"band {s.BandRows} rows (stroke at most {s.MaxBandRows}), " +
                         $"{(s.CapTrimmed ? "trimmed" : "not trimmed")} by the stroke cap")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>How far a swept point's height or depth may shrink from before: 3 px below 21.3 px where the
    /// cap at the flag's own stroke trimmed the band, 2 px everywhere else (see
    /// <see cref="SweepHeightAndDepthDriftAtMostTwoPixels"/>).</summary>
    private static float ShrinkLimitPx(Swept s) =>
        s.Before.Size < SmallSizeShrinkBelow && s.CapTrimmed ? SmallSizeShrinkLimitPx : DriftLimitPx;

    /// <summary>
    /// The 3 px shrink allowance is not every point below 21.3 px. Its condition used to be that the band
    /// was within the flag's stroke, which <see cref="SweepBandIsNeverMoreRowsThanTheFlagsStroke"/> makes
    /// true at every point, so the allowance covered all of them. It now covers only the points where the
    /// stroke cap trimmed the band, and the sweep has both kinds below 21.3 px, so the 2 px limit holds at
    /// some of them.
    /// </summary>
    [Fact]
    public void TheSmallSizeShrinkAllowanceIsNotEveryPointBelow21Px()
    {
        var below = SweptPoints.Value.Where(s => s.Before.Size < SmallSizeShrinkBelow).ToList();
        var allowed = below.Count(s => ShrinkLimitPx(s) == SmallSizeShrinkLimitPx);
        allowed.ShouldBeGreaterThan(0, "points below 21.3 px where the stroke cap trimmed the band");
        allowed.ShouldBeLessThan(below.Count, $"points below 21.3 px given the 3 px allowance, of {below.Count}");
    }

    /// <summary>
    /// Across the sweep the radicand never has fewer clear rows under the bar than before, at any size, in
    /// either font, in any scene. The rework's bar sat on the floor of a float, so whether a row of the gap
    /// stayed clear depended on the float phase, and three relaxations stood in for this rule: no touching
    /// from 21.3 px where the old code left a clear row, at most one row lost there, and touching no more
    /// common below it. STIX Two Math <c>\sqrt{\frac{a}{b}}</c> at 22.2 px and
    /// <c>\sqrt{\frac{\frac{a}{b}}{\frac{c}{d}}}</c> at 31.7 px went from 3 clear rows to 2 (see
    /// <see cref="TheRowsFloatPhaseCostKeepThreeClearRows"/>). The gap is now kept in whole rows at draw
    /// time, so no row is left to rounding. Every failing point is listed in the one message.
    /// </summary>
    [Fact]
    public void SweepNeverHasFewerClearRowsThanBefore()
    {
        var failures = SweptPoints.Value
            .Where(s => s.ClearRows < s.Before.ClearRows)
            .Select(s => $"{s}: {s.ClearRows} clear rows under the bar, before {s.Before.ClearRows}")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>
    /// At every point of the sweep the radicand keeps at least one clear row under the bar. Below 21.3 px the
    /// 0.12 em gap is under two pixels, and the radicand's own antialiased top can sit a row or two above its
    /// layout height, so a gap left to rounding let the two touch: at 758 of the 2401 points as fe09d4a drew
    /// them, 791 as e6778fc did. Every failing point is listed in the one message.
    /// </summary>
    [Fact]
    public void SweepKeepsAClearRowUnderTheBar()
    {
        var failures = SweptPoints.Value
            .Where(s => s.Touches)
            .Select(s => $"{s}: the radicand touches the bar (before {s.Before.ClearRows} clear rows)")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>
    /// Raising the bar to keep its whole rows moves the glyph up, never down: across the sweep, and with the
    /// radical in a fraction's numerator at every swept size, the glyph's bitmap ends at or above the
    /// bottom the radical reports, <c>baselineY + Depth</c>, as the floored placement always kept it. A
    /// parent lays out against that bottom (a fraction keeps it a gap above its rule), so a glyph drawn a
    /// row below its layout hangs its tip into the gap: placing the bar a fixed number of rows above the
    /// radicand's top row, wherever the floor had put the glyph, did that to <c>\frac{\sqrt{\pi}}{2}</c>
    /// at 96 px. Every failing point is listed in the one message.
    /// </summary>
    [Fact]
    public void TheGlyphNeverReachesPastTheReportedDepth()
    {
        const float floatNoise = 2e-3f;
        var numerator = from font in FontPaths.Keys
                        from size in SweepSizes
                        let r = Render(font, size, "frac-sqrt-x")
                        select (Name: $"{font} frac-sqrt-x {size} px", r.GlyphPastDepth, r.Sqrt.Depth);
        var failures = SweptPoints.Value
            .Select(s => (Name: s.ToString(), s.GlyphPastDepth, s.Depth))
            .Concat(numerator)
            .Where(p => p.GlyphPastDepth > floatNoise)
            .Select(p => $"{p.Name}: the glyph reaches {p.GlyphPastDepth} px past its depth {p.Depth}")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>
    /// Where the radicand's own ink starts a row or two above its layout height (sizes below 12 px), the draw
    /// raises the bar past what the layout placed, and it can go past the row of headroom the layout reserves
    /// for that too: the one place the radical's box does not hold its ink. Across the sweep and
    /// <see cref="ContextScenes"/> that is at most 2 rows above the reported height (one, at 7 points, since
    /// the headroom row); the glyph and bar always lie on the canvas
    /// <see cref="BoxRasterizer.RenderToRgba"/> draws on, whose margin of ceil(0.15 em) is all there is above
    /// the outermost box; and the canvas cuts off no more of the scene's ink than it did at fe09d4a (see
    /// <see cref="InkCutOff"/>). It does cut some: STIX Two Math <c>\sqrt{\frac{\frac{a}{b}}{\frac{c}{d}}}</c>
    /// takes a MATH assembly shorter than its radicand, whose depth path 1 does not count, so the radicand
    /// hangs below the canvas at 119 of its 238 sizes there as here. Every failing point is listed in the
    /// one message.
    /// </summary>
    [Fact]
    public void TheRaisedBarNeverClips()
    {
        const int maxRowsAboveHeight = 2;
        var failures = SweptPoints.Value
            .Where(s => s.RowsAboveHeight > maxRowsAboveHeight || !s.RadicalOnCanvas || s.InkCutOff > s.Before.CutOff)
            .Select(s => $"{s}: the bar sits {s.RowsAboveHeight} rows above the reported height, the radical is " +
                         $"{(s.RadicalOnCanvas ? "on" : "off")} the canvas, which cut off {s.InkCutOff} alpha, before {s.Before.CutOff}")
            .ToList();
        failures.ShouldBeEmpty(Environment.NewLine + string.Join(Environment.NewLine, failures));
    }

    /// <summary>
    /// The bar continues the flag at every point of the sweep, not only at the join assertions' three sizes:
    /// no gap column between them and no row of offset. The draw places glyph and bar from the one join, so
    /// raising the bar to keep its clear row raises the glyph with it; this holds that at every point,
    /// among them the 61 where the radicand's ink raises the bar (by two rows at STIX Two Math
    /// <c>\sqrt{2}</c> 7.6 and 7.65 px). Every failing point is listed in the one message.
    /// </summary>
    [Fact]
    public void SweepBarStaysJoinedToTheFlag()
    {
