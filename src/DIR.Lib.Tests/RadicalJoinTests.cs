    private static void AssertBandAndMetrics(string font, string scene, float size)
    {
        var before = BeforeAt(font, scene, size);
        var r = Render(font, size, scene);
        r.Join.FlagRows.ShouldBeLessThanOrEqualTo(MaxBandRows(font, r), "rows of the bar's band");
        r.Sqrt.Height.ShouldBe(before.Height, DriftLimitPx, "radical height");
        r.Sqrt.Depth.ShouldBe(before.Depth, DriftLimitPx, "radical depth");
    }

    private static BeforePoint BeforeAt(string font, string scene, float size) =>
        BeforePoints.Single(p => p.Font == font && p.Scene == scene && p.Size == size);

    private sealed record Rendered(RgbaImage Image, SqrtBox Sqrt, SqrtBox.RadicalJoin Join)
    {
        public int Alpha(int x, int y) =>
            x < 0 || y < 0 || x >= Image.Width || y >= Image.Height ? 0 : Image.Pixels[(y * Image.Width + x) * 4 + 3];

        public int ColumnSum(int x)
        {
            var sum = 0;
            for (var y = Join.FlagTopY; y < Join.FlagTopY + Join.FlagRows; y++) sum += Alpha(x, y);
            return sum;
        }

        /// <summary>Rows with no ink at all, under the bar's columns (from the glyph's right edge to the bar's
        /// end), between the bar's last row and the first row below it that has ink: the radicand's top.</summary>
        public int ClearRowsUnderBar()
        {
            var below = Join.FlagTopY + Join.FlagRows;
            var y = below;
            while (y < Image.Height && !RowHasInk(y)) y++;
            return y - below;
        }

        private bool RowHasInk(int y)
        {
            for (var x = Join.BarStartX; x < Join.BarEndX; x++)
                if (Alpha(x, y) > 0) return true;
            return false;
        }
    }

    private static Rendered Render(string font, float size, string scene)
    {
        var style = new BoxStyle(FontPaths[font], size, new RGBAColor32(0, 0, 0, 255));
        var box = scene switch
        {
            "sqrt-x2-plus-y2" => Parse(@"\sqrt{x^2+y^2}", style),
            "sqrt-2" => Parse(@"\sqrt{2}", style),
            "sqrt-x" => Parse(@"\sqrt{x}", style),
            "sqrt-frac-a-b" => Parse(@"\sqrt{\frac{a}{b}}", style),
            "quadratic-formula" => Parse(@"\frac{-b \pm \sqrt{b^2-4ac}}{2a}", style),
            // The index goes through the Box API: the grammar's \sqrt takes no optional argument.
            "index-box-api" => new SqrtBox(
                new MathGlyphBox("x", style, MathStyle.Italic),
                new GlyphBox("3", style.Smaller().Smaller()),
                style),
            "sqrt-paren-frac" => Parse(@"\sqrt{\left(\frac{a}{b}\right)}", style),
            "sqrt-nested-frac" => Parse(@"\sqrt{\frac{\frac{a}{b}}{\frac{c}{d}}}", style),
            _ => throw new ArgumentException($"unknown scene '{scene}'"),
        };

        var (root, probe) = ProbeSqrt(box);
        var image = BoxRasterizer.RenderToRgba(root, style);
        var (penX, baselineY) = probe.Pen.ShouldNotBeNull("the scene never drew its radical");
        var join = probe.Sqrt.JoinAt(penX, baselineY).ShouldNotBeNull("the radical has no flag and bar (parametric path?)");
        join.FlagRows.ShouldBeGreaterThan(0);
        join.BarEndX.ShouldBeGreaterThan(join.FlagLastFullX);
        return new Rendered(image, probe.Sqrt, join);
    }

    private static Box Parse(string latex, BoxStyle style)
    {
        if (!MarkdownMacros.TryPrepareMathBoxSource(latex, out var src))
            Assert.Fail($"'{latex}' was turned away from the box path");
        var parser = Latex.BuildParser(new BoxBuildingVisitor(style));
        using var lexer = BytesLexer.FromString(src, MarkdownMacros.MathLexerTable);
        using var tokens = new SyncLATokenIterator(lexer);
        var item = parser.ParseInput(tokens, debugger: null);
        item.IsError.ShouldBeFalse($"'{latex}' did not parse");
        return item.Content.ShouldBeOfType<Func<BoxStyle, Box>>()(style);
    }

    /// <summary>
    /// Stands in for the scene's radical in its parent's slot and records the pen the parent draws it at,
    /// so the test can ask the radical where its join is for that pen. It forwards the radical's metrics
    /// and its draw unchanged, so the scene lays out and paints exactly as it does without it; the record
    /// is the test's own, and the radical's draw writes none.
    /// </summary>
    private sealed class PenProbe(SqrtBox sqrt) : Box
    {
        public SqrtBox Sqrt => sqrt;

        public (float PenX, float BaselineY)? Pen { get; private set; }

        public override float Width => sqrt.Width;
        public override float Height => sqrt.Height;
        public override float Depth => sqrt.Depth;

        public override void Draw(RgbaImageRenderer renderer, float penX, float baselineY, BoxStyle style)
        {
            Pen = (penX, baselineY);
            sqrt.Draw(renderer, penX, baselineY, style);
        }
    }

    /// <summary>The scene with a <see cref="PenProbe"/> in place of its one radical, and that probe. Boxes
    /// keep their children in private fields, so this walks them and swaps the radical where its parent
    /// holds it; the scene itself is the radical when it is the root.</summary>
    private static (Box Root, PenProbe Probe) ProbeSqrt(Box root)
    {
        if (root is SqrtBox top)
        {
            var probe = new PenProbe(top);
            return (probe, probe);
        }

        var seen = new HashSet<object>(ReferenceEqualityComparer.Instance);
        var pending = new Stack<object>();
        pending.Push(root);
        while (pending.TryPop(out var node))
        {
            if (!seen.Add(node)) continue;
            for (var type = node.GetType(); type is not null && type != typeof(object); type = type.BaseType)
            {
                foreach (var field in type.GetFields(BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public | BindingFlags.DeclaredOnly))
                {
                    switch (field.GetValue(node))
                    {
                        case SqrtBox sqrt when field.FieldType.IsAssignableFrom(typeof(PenProbe)):
                        {
                            var probe = new PenProbe(sqrt);
                            field.SetValue(node, probe);
                            return (root, probe);
                        }
                        case Box child:
                            pending.Push(child);
                            break;
                        case System.Collections.IList items when items.GetType().GetElementType() is { } element
                                                                 && element.IsAssignableFrom(typeof(PenProbe)):
                            for (var i = 0; i < items.Count; i++)
                            {
                                if (items[i] is SqrtBox sqrt)
                                {
                                    var probe = new PenProbe(sqrt);
                                    items[i] = probe;
                                    return (root, probe);
                                }
                                if (items[i] is Box b) pending.Push(b);
                            }
                            break;
                        case System.Collections.IEnumerable items and not string:
                            foreach (var item in items)
                                if (item is Box b) pending.Push(b);
                            break;
                    }
                }
            }
        }
        throw new InvalidOperationException("scene has no SqrtBox its parent holds in a slot a probe fits");
    }
