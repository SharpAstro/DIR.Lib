    private sealed record Rendered(RgbaImage Image, SqrtBox Sqrt, SqrtBox.RadicalJoin Join, float BaselineY)
    {
        /// <summary>How far, in pixels, the glyph's bitmap reaches below the radical's reported bottom,
        /// <c>baselineY + Depth</c>; zero or less when it stays inside.</summary>
        public float GlyphPastDepth => Join.GlyphY + Join.GlyphRows - (BaselineY + Sqrt.Depth);

        /// <summary>Whole rows the bar's top sits above the row holding the radical's reported top,
        /// <c>baselineY - Height</c>: zero where the box contains it.</summary>
        public int RowsAboveHeight => Math.Max(0, (int)MathF.Floor(BaselineY - Sqrt.Height + 1e-3f) - Join.FlagTopY);

        /// <summary>Whether the radical's own ink, its glyph and bar, lies on the canvas: from the flag's
        /// top row (the glyph's top ink) to the glyph's last row, and from the glyph's left edge to the
        /// bar's end.</summary>
        public bool RadicalOnCanvas =>
            Join.FlagTopY >= 0 && Join.GlyphY + Join.GlyphRows <= Image.Height && Join.GlyphX >= 0 && Join.BarEndX <= Image.Width;

        /// <summary>Where the bar fails to continue the flag, or null where it does: a column from the flag's
        /// last full column to the bar's end lighter than that column down the band (a gap column, which is
        /// what <see cref="NoColumnAtTheJoinIsLighterThanTheBar"/> asserts at its three sizes), or a bar
        /// column whose band rows and the row above them differ from the flag's column (an offset row, which
        /// is what <see cref="BarRepeatsTheFlagsLastFullColumn"/> asserts there).</summary>
        public string? JoinBreak()
        {
            var j = Join;
            var reference = ColumnSum(j.FlagLastFullX);
            for (var x = j.FlagLastFullX; x < j.BarEndX; x++)
                if (ColumnSum(x) < reference - AlphaTolerance * j.FlagRows)
                    return $"column {x} has {ColumnSum(x)} alpha down the band against the flag's {reference}";
            for (var x = j.FlagLastFullX + 1; x < j.BarEndX; x++)
                for (var y = j.FlagTopY - 1; y < j.FlagTopY + j.FlagRows; y++)
                    if (Math.Abs(Alpha(x, y) - Alpha(j.FlagLastFullX, y)) > AlphaTolerance)
                        return $"column {x}, row {y}: {Alpha(x, y)} against the flag's {Alpha(j.FlagLastFullX, y)} (band {j.FlagTopY}..{j.FlagTopY + j.FlagRows - 1})";
            return null;
        }

        public int Alpha(int x, int y) =>
            x < 0 || y < 0 || x >= Image.Width || y >= Image.Height ? 0 : Image.Pixels[(y * Image.Width + x) * 4 + 3];

        public int ColumnSum(int x)
        {
            var sum = 0;
            for (var y = Join.FlagTopY; y < Join.FlagTopY + Join.FlagRows; y++) sum += Alpha(x, y);
            return sum;
        }

        /// <summary>Rows with no ink at all, under the bar's columns (from the glyph's right edge to the bar's
        /// end), between the bar's last row and the first row below it that has ink: the radicand's top.</summary>
        public int ClearRowsUnderBar()
        {
            var below = Join.FlagTopY + Join.FlagRows;
            var y = below;
            while (y < Image.Height && !RowHasInk(y)) y++;
            return y - below;
        }

        /// <summary>Rows with no ink at all, under the bar's columns, between the bar's top row and the first
        /// row above it that has ink (a fraction's rule), or the canvas's top edge where none has.
        /// tools/gen-radical-join-before counts fe09d4a's the same way.</summary>
        public int ClearRowsAboveBar()
        {
            var above = Join.FlagTopY - 1;
            while (above >= 0 && !RowHasInk(above)) above--;
            return Join.FlagTopY - 1 - above;
        }

        private bool RowHasInk(int y)
        {
            for (var x = Join.BarStartX; x < Join.BarEndX; x++)
                if (Alpha(x, y) > 0) return true;
            return false;
        }
    }

    private static Rendered Render(string font, float size, string scene)
    {
        var style = new BoxStyle(FontPaths[font], size, new RGBAColor32(0, 0, 0, 255));
        var box = BuildScene(scene, style);
        var (root, probe) = ProbeSqrt(box);
        var image = BoxRasterizer.RenderToRgba(root, style);
        var (penX, baselineY, drawnStyle) = probe.Pen.ShouldNotBeNull("the scene never drew its radical");
        var join = probe.Sqrt.JoinAt(penX, baselineY, drawnStyle).ShouldNotBeNull("the radical has no flag and bar (parametric path?)");
        join.FlagRows.ShouldBeGreaterThan(0);
        join.BarEndX.ShouldBeGreaterThan(join.FlagLastFullX);
        return new Rendered(image, probe.Sqrt, join, baselineY);
    }

    private static Box BuildScene(string scene, BoxStyle style) =>
        scene switch
        {
            "sqrt-x2-plus-y2" => Parse(@"\sqrt{x^2+y^2}", style),
            "sqrt-2" => Parse(@"\sqrt{2}", style),
            "sqrt-x" => Parse(@"\sqrt{x}", style),
            "sqrt-frac-a-b" => Parse(@"\sqrt{\frac{a}{b}}", style),
            "quadratic-formula" => Parse(@"\frac{-b \pm \sqrt{b^2-4ac}}{2a}", style),
            // The index goes through the Box API: the grammar's \sqrt takes no optional argument.
            "index-box-api" => IndexScene(style, blankIndex: false),
            "sqrt-paren-frac" => Parse(@"\sqrt{\left(\frac{a}{b}\right)}", style),
            "sqrt-nested-frac" => Parse(@"\sqrt{\frac{\frac{a}{b}}{\frac{c}{d}}}", style),
            // A radical whose baseline its parent places: a fraction keeps its numerator a gap above the
            // rule by the depth the numerator reports.
            "frac-sqrt-x" => Parse(@"\frac{\sqrt{x}}{2}", style),
            "frac-1-sqrt-x" => Parse(@"\frac{1}{\sqrt{x}}", style),
            "frac-1-sqrt-frac-a-b" => Parse(@"\frac{1}{\sqrt{\frac{a}{b}}}", style),
            "x-sup-sqrt-y" => Parse(@"x^{\sqrt{y}}", style),
            "frac-1-sqrt-hat-x" => Parse(@"\frac{1}{\sqrt{\hat{x}}}", style),
            "frac-1-sqrt-sum-x" => Parse(@"\frac{1}{\sqrt{\sum x}}", style),
            "frac-1-sqrt-paren-x" => Parse(@"\frac{1}{\sqrt{\left(x\right)}}", style),
            _ => throw new ArgumentException($"unknown scene '{scene}'"),
        };

    /// <summary>
    /// How much of the scene's ink the canvas <see cref="BoxRasterizer.RenderToRgba"/> drew it on cut off: the
    /// scene drawn again at the same coordinates on a canvas 8 px larger on every side, less the ink on
    /// <paramref name="canvas"/>. The larger canvas moves the writes by a content transform, an integer
    /// translation, so every position is computed exactly as before and only what the edge cut off differs.
    /// </summary>
    private static long InkCutOff(string font, float size, string scene, RgbaImage canvas)
    {
        const int pad = 8;
        var style = new BoxStyle(FontPaths[font], size, new RGBAColor32(0, 0, 0, 255));
        var box = BuildScene(scene, style);
        // RenderToRgba's own margin, read back from the canvas it made: ceil(width) plus a margin each side.
        var margin = (canvas.Width - (int)MathF.Ceiling(box.Width)) / 2;
        using var renderer = new RgbaImageRenderer((uint)(canvas.Width + 2 * pad), (uint)(canvas.Height + 2 * pad));
        renderer.ContentTransform = new ContentTransform(Rotation90.None, 1f, pad, pad);
        box.Draw(renderer, margin, margin + box.Height, style);
        return InkSum(renderer.Surface) - InkSum(canvas);
    }

